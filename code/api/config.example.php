<?php
/* ==========================================================================
   config.example.php · 配置模板
   复制成 config.php 再填。config.php 已被 .gitignore 排除，不会进版本库 ——
   里面有口令哈希和高德 key，不能提交。

   复制方式（在服务器上）：
     cp api/config.example.php api/config.php
   或者在 FTP 里下载下来改好名字再传回去。

   ⚠️ 部署前置条件：PHP ≥ 7.4。四个接口用了箭头函数、
   session_set_cookie_params 的数组形式、数组解构；低于 7.4 会**解析错误**
   → 接口全部 500 空白，而 display_errors=0 让页面完全无提示。
   InfinityFree 账号默认版本可能是 7.0/7.2，请先在控制面板切成 7.4 或 8.x。
   ========================================================================== */

return [
    /* ------------------------------------------------------------------
       管理口令
       先生成一个哈希：在服务器上建一个临时 php 文件写入
           <?php echo password_hash('你的口令', PASSWORD_DEFAULT);
       打开它拿到输出，粘到这里，然后删掉那个临时文件。
       占位符状态下任何口令都进不去，必须先替换。
       ------------------------------------------------------------------ */
    'password_hash' => '',

    /* ------------------------------------------------------------------
       高德 Web 服务 key
       留空则自动退回内置地点库，功能依然可用。
       key 只放在服务端，不会出现在网页源码里。
       ------------------------------------------------------------------ */
    'amap_key' => '',

    /* ------------------------------------------------------------------
       HTTPS
       ⚠️ 默认改成 true 了。私有站点，口令和 30 天 session 只该走加密连接：
       原来默认 false，而 secure cookie 的判定又依赖 $_SERVER['HTTPS']
       或 X-Forwarded-Proto —— 在反代终止的环境里这两个常常都拿不到 →
       会话 cookie 被判成非安全 → 同一 WiFi 上被动监听就能接管会话，
       进而改数据、传文件。

       InfinityFree 默认提供免费 SSL 证书，直接用 HTTPS 访问即可。
       万一站点确实只有 HTTP（打不开），改回 false 立刻恢复 ——
       但那样口令就是明文过网了。
       ------------------------------------------------------------------ */
    'force_https' => true,

    /* ------------------------------------------------------------------
       路径
       ⚠️ config.php 本身在文档根目录内。api/.htaccess 已经用
       `Require all denied` + FilesMatch 白名单挡住了直接访问，
       但别在这份文件里加任何 echo/var_dump —— 那样一旦 PHP 处理器
       关联错位，口令哈希与高德 key 会明文躺在公网目录里。
       ------------------------------------------------------------------ */
    'data_dir'    => dirname(__DIR__) . '/data',
    'uploads_dir' => dirname(__DIR__) . '/uploads',
    // 相对页面根目录的路径。照片最终会以 "uploads/xxx.webp" 的形式出现在 img 的 src 里，
    // 这样无论站点部署在根目录还是子目录都能正确解析。
    'uploads_url' => 'uploads',

    /* ------------------------------------------------------------------
       上传限制
       ⚠️ max_file_mb 是**单张**上限，但一次请求会同时发 full + thumb
       两个文件（见 upload.php 的 foreach），总和受服务器的 post_max_size
       约束。InfinityFree 免费机的 post_max_size 常见为 8M，
       两张 8MB 的图就超了 —— PHP 会**清空整个 $_FILES**，
       前端收到的是「没有收到文件」，而真实原因是文件太大。
       前端已按总大小预检，见 store.js 的 uploadPhoto。
       ------------------------------------------------------------------ */
    'max_file_mb'      => 8,
    'max_uploads_hour' => 120,
    'max_writes_hour'  => 60,
];
