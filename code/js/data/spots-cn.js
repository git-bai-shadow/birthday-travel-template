const SPOTS = RAW.map(([name, city, lat, lon], i) => ({ id: `s${i}`, name, city, lat, lon }));

/** 在城市或名称里做包含匹配，名称命中的排在前面 */
export function search(q, limit = 6) {
  const key = String(q).trim().toLowerCase();
  if (!key) return [];

  const hits = [];
  for (const s of SPOTS) {
    const nameHit = s.name.toLowerCase().includes(key);
    const cityHit = s.city.toLowerCase().includes(key);

    if (nameHit) hits.push({ ...s, score: s.name.toLowerCase().startsWith(key) ? 0 : 1 });
    else if (cityHit) hits.push({ ...s, score: 2 });
  }

  return hits
    .sort((a, b) => a.score - b.score || a.name.length - b.name.length)
    .slice(0, limit)
    .map((s) => ({ name: s.name, city: s.city, lat: s.lat, lon: s.lon, source: 'builtin' }));
}

/** 按城市名取中心点，用于城市级打点 */
export function cityCenter(city) {
  const key = String(city).trim().toLowerCase();
  const hit = SPOTS.find((s) => s.city.toLowerCase() === key);
  return hit ? { lat: hit.lat, lon: hit.lon } : null;
}

export default { search, cityCenter, all: SPOTS };
